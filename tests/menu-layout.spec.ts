import { test, expect } from "@playwright/test";
import { createHash } from "node:crypto";

test("menu groups ingredients with beverages last and keeps a compact responsive form", async ({ page }, info) => {
  await page.setViewportSize({ width: 1920, height: 1000 });
  await page.route("**/users", (route) => route.fulfill({ json: [{ id: "admin", username: "admin", role: "admin", password: createHash("md5").update("test").digest("hex") }] }));
  await page.goto("/login");
  await page.getByLabel("Usuario", { exact: true }).fill("admin");
  await page.locator('input[type="password"]').fill("test");
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/\/operation$/);
  await page.goto("/menu-products");
  const editor = page.locator("section").filter({ has: page.getByRole("heading", { name: "Ingredientes", exact: true }) }).last();
  await expect(editor.getByRole("region").last()).toHaveAccessibleName("Bebidas");
  await expect(editor.getByRole("region").locator("h4")).toHaveText(["Panificados (6)▾", "Carnes (8)▾", "Lacteos (4)▾", "Vegetales (9)▾", "Salsas (5)▾", "Sin categoria (3)▾", "Bebidas (12)▸"]);
  const beverages = editor.getByRole("region", { name: "Bebidas", exact: true });
  const beverageToggle = beverages.getByRole("button", { name: /^Bebidas/ });
  await expect(beverageToggle).toHaveAttribute("aria-expanded", "false");
  await expect(beverages.getByRole("button", { name: /Pepsi Lata/ })).toBeHidden();
  await beverageToggle.click();
  await expect(beverageToggle).toHaveAttribute("aria-expanded", "true");
  await expect(beverages.getByText(/desplaza para ver mas/)).toHaveCount(0);
  await beverageToggle.click();
  const meatGroup = editor.getByRole("region", { name: "Carnes", exact: true });
  const meatList = meatGroup.locator('[aria-label="Ingredientes de Carnes"]');
  expect(await meatList.evaluate((node) => node.offsetWidth - node.clientWidth)).toBeLessThanOrEqual(2);
  const groupBounds = await meatGroup.boundingBox();
  const scrollBounds = await meatList.boundingBox();
  expect(groupBounds!.x + groupBounds!.width - scrollBounds!.x - scrollBounds!.width).toBeCloseTo(1, 0);
  expect(await meatList.evaluate((node) => {
    const bounds = node.getBoundingClientRect();
    const visible = Array.from(node.querySelectorAll("button")).filter((button) => {
      const box = button.getBoundingClientRect();
      return box.top >= bounds.top && box.bottom <= bounds.bottom;
    });
    return node.scrollHeight > node.clientHeight && visible.length === 7;
  })).toBe(true);
  await meatList.getByRole("button").last().scrollIntoViewIfNeeded();
  expect(await meatList.evaluate((node) => node.scrollTop)).toBeGreaterThan(0);
  await meatList.evaluate((node) => { node.scrollTop = 0; });
  await meatGroup.getByRole("button", { name: /^Carnes/ }).click();
  await expect(meatList).toBeHidden();
  await meatGroup.getByRole("button", { name: /^Carnes/ }).click();
  await expect(meatList).toBeVisible();
  await expect(editor.getByRole("region", { name: "Panificados", exact: true })).toBeVisible();
  await expect(editor.getByRole("region", { name: "Sin categoria", exact: true }).getByRole("button", { name: /Huevo/ })).toBeVisible();
  await editor.getByRole("region", { name: "Panificados", exact: true }).getByRole("button", { name: /^Pan de Hamburguesa/ }).click();
  const selected = page.getByRole("list", { name: "Ingredientes seleccionados" });
  await expect(selected.getByRole("status", { name: "Cantidad de Pan de Hamburguesa en receta", exact: true })).toHaveText("1 u.");
  const requirement = selected.getByRole("group", { name: "Tipo de ingrediente: Pan de Hamburguesa", exact: true });
  await expect(requirement.getByRole("button", { name: "Obligatorio", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(requirement.getByRole("button", { name: "Opcional", exact: true })).toBeDisabled();
  await expect(selected.getByRole("spinbutton")).toHaveCount(0);
  await editor.getByRole("region", { name: "Panificados", exact: true }).getByRole("button", { name: /^Pan de Hamburguesa/ }).click();
  await expect(selected.getByRole("status", { name: "Cantidad de Pan de Hamburguesa en receta", exact: true })).toHaveText("2 u.");
  await editor.getByRole("region", { name: "Sin categoria", exact: true }).getByRole("button", { name: /^Huevo/ }).click();
  await requirement.getByRole("button", { name: "Opcional", exact: true }).click();
  await expect(selected.getByRole("listitem").first()).toContainText("Pan de Hamburguesa");
  await expect(selected.getByRole("listitem").last()).toContainText("Huevo");
  const subtractBread = selected.getByRole("button", { name: "Restar Pan de Hamburguesa", exact: true });
  await expect(editor.getByRole("button", { name: /^Restar / })).toHaveCount(0);
  await subtractBread.click();
  await expect(selected.getByRole("status", { name: "Cantidad de Pan de Hamburguesa en receta", exact: true })).toHaveText("1 u.");
  await subtractBread.click();
  await expect(subtractBread).toHaveCount(0);
  await expect(selected.getByRole("listitem")).toHaveCount(1);
  await editor.getByRole("region", { name: "Panificados", exact: true }).getByRole("button", { name: /^Pan de Hamburguesa/ }).click();
  await expect(selected.getByRole("listitem").last()).toContainText("Pan de Hamburguesa");
  await selected.getByRole("button", { name: "Quitar Huevo", exact: true }).click();
  const groups = editor.getByRole("region");
  const firstGroup = await groups.nth(0).boundingBox();
  const fourthGroup = await groups.nth(3).boundingBox();
  expect(Math.abs(firstGroup!.y - fourthGroup!.y)).toBeLessThan(2);
  expect(fourthGroup!.x).toBeGreaterThan(firstGroup!.x);
  const name = await page.getByLabel("Nombre", { exact: true }).boundingBox();
  const price = await page.getByLabel("Precio de venta", { exact: true }).boundingBox();
  const category = await page.getByRole("combobox", { name: "Categoria", exact: true }).boundingBox();
  const description = await page.getByLabel("Descripcion", { exact: true }).boundingBox();
  expect(Math.abs(name!.y - price!.y)).toBeLessThan(2);
  expect(Math.abs(category!.y - description!.y)).toBeLessThan(2);
  expect(Math.abs(name!.y - category!.y)).toBeLessThan(2);
  expect(name!.width).toBeGreaterThan(price!.width * 1.5);
  const formCard = page.locator("section").filter({ has: page.getByRole("heading", { name: "Crear producto de menu", exact: true }) }).first();
  const listCard = page.locator("section").filter({ has: page.getByRole("heading", { name: "Menu actual", exact: true }) }).first();
  const formBounds = await formCard.boundingBox();
  const listBounds = await listCard.boundingBox();
  expect(formBounds!.width / listBounds!.width).toBeCloseTo(65 / 35, 1);
  const submit = await page.getByRole("button", { name: "Crear producto", exact: true }).boundingBox();
  expect(submit!.x + submit!.width).toBeLessThanOrEqual(formBounds!.x + formBounds!.width);
  await expect(formCard.getByText("Precio", { exact: true })).toHaveCount(0);
  await expect(page.getByText("Produccion con stock", { exact: true })).toHaveCount(0);
  await expect(listCard.getByText(/\d+ (ingredientes|porciones)/)).toHaveCount(0);
  const categoryFilter = listCard.getByRole("combobox", { name: "Categoria del menu actual" });
  await expect(categoryFilter).toHaveValue("all");
  await expect(categoryFilter.locator("option").first()).toHaveText(/^Todas \(\d+\)$/);
  const catalogSearch = listCard.getByRole("textbox", { name: "Buscar producto por nombre" });
  await catalogSearch.fill("Pepsi");
  await expect(listCard.getByRole("button")).toHaveCount(1);
  await expect(listCard.getByRole("button")).toContainText("Pepsi Lata x 1");
  await catalogSearch.fill("producto-inexistente-000");
  await expect(listCard.getByText("No hay productos de menu para mostrar.")).toBeVisible();
  await catalogSearch.clear();
  const left = await editor.boundingBox();
  const right = await page.getByRole("heading", { name: "Menu actual", exact: true }).boundingBox();
  expect(left!.x + left!.width).toBeLessThan(right!.x);
  await page.screenshot({ path: info.outputPath("menu-desktop.png"), fullPage: true });
  for (const width of [1920, 1440, 1280, 1050, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    const bounds = await formCard.boundingBox();
    for (const control of [page.getByLabel("Nombre", { exact: true }), page.getByLabel("Precio de venta", { exact: true }), page.getByRole("combobox", { name: "Categoria", exact: true }), page.getByLabel("Descripcion", { exact: true }), page.getByRole("button", { name: "Crear producto", exact: true })]) {
      const box = await control.boundingBox();
      expect(box!.x).toBeGreaterThanOrEqual(bounds!.x);
      expect(box!.x + box!.width).toBeLessThanOrEqual(bounds!.x + bounds!.width);
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("menu-mobile.png"), fullPage: true });
  await selected.getByRole("button", { name: "Quitar Pan de Hamburguesa", exact: true }).click();
  await expect(selected).toHaveCount(0);
});
